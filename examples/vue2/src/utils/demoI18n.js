/**
 * Translate a demo UI string by (zh, en) pair.
 * zh-CN and en-US use the literals directly; other locales use the generated packs.
 */
export function demoT(locale, zh, en) {
  if (locale === 'zh-CN') return zh
  if (locale === 'en-US') return en
  const i = KEYS.indexOf(en)
  if (i < 0) return en
  return PACKS[locale]?.[i] || en
}
